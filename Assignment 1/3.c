// Assignment 1: Problem 3
// Write a C program to subtract between two numbers.

#include <stdio.h>

int main() {
    int num1, num2, difference;

    num1 = 50;
    num2 = 18;

    difference = num1 - num2;

    printf("The difference between %d and %d is: %d\n", num1, num2, difference);

    return 0;
}